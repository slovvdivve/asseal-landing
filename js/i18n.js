function assealApplyLang(lang) {
  const dict = ASSEAL_I18N[lang] || ASSEAL_I18N.ru;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  const label = document.getElementById("langToggleLabel");
  if (label) label.textContent = lang === "ru" ? "EN" : "РУ";
  localStorage.setItem("asseal_lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const saved = localStorage.getItem("asseal_lang") || "ru";
  assealApplyLang(saved);

  const toggle = document.getElementById("langToggle");
  toggle?.addEventListener("click", () => {
    const current = document.documentElement.lang === "ru" ? "en" : "ru";
    assealApplyLang(current);
  });
});
